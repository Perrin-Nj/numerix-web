// Bundles contracts/wiremock/mappings/*.json into lib/mappings.mjs so the function needs no file access.
// Run after changing the mock: node contracts/wiremock/gen.mjs && node mock/scripts/sync-mappings.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('..', import.meta.url));
const dir = join(here, '..', 'contracts', 'wiremock', 'mappings');
const all = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));
writeFileSync(join(here, 'lib', 'mappings.mjs'), `// Generated by scripts/sync-mappings.mjs. Do not edit.\nexport default ${JSON.stringify(all)};\n`);
console.log(`bundled ${all.length} mappings`);
